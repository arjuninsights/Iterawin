CREATE TABLE app_users (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(254) NOT NULL UNIQUE,
  password_hash VARCHAR2(300) NOT NULL,
  user_role VARCHAR2(10) DEFAULT 'client' NOT NULL CHECK (user_role IN ('client','owner')),
  is_active NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  last_login TIMESTAMP
);
CREATE TABLE content_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR2(10) NOT NULL CHECK (kind IN ('tech','project','post')),
  payload CLOB NOT NULL CONSTRAINT content_payload_json CHECK (payload IS JSON),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX content_kind_idx ON content_items (kind);
