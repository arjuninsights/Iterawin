"""Database layer. Oracle (python-oracledb, thin mode) by default.
Set DB=sqlite to run locally without Oracle (testing only)."""
import os, json, sqlite3
from contextlib import contextmanager
from pathlib import Path
from werkzeug.security import generate_password_hash

BASE = Path(__file__).parent
KIND = 'sqlite' if os.getenv('DB', 'oracle').lower() == 'sqlite' else 'oracle'
SQLITE_PATH = os.getenv('SQLITE_PATH', str(BASE / 'iterawin.db'))

if KIND == 'oracle':
    import oracledb
    oracledb.defaults.fetch_lobs = False          # CLOB columns come back as str
    IntegrityErrors = (oracledb.IntegrityError,)
else:
    IntegrityErrors = (sqlite3.IntegrityError,)

_pool = None
def _get_pool():
    global _pool
    if _pool is None:
        kw = dict(user=os.environ['system'], password=os.environ['arjun'],
                  dsn=os.environ['orcldb'], min=1, max=int(os.getenv('ORACLE_POOL_MAX', '4')), increment=1)
        wd = os.getenv('ORACLE_WALLET_DIR')       # Autonomous Database wallet folder (optional)
        if wd:
            kw.update(config_dir=wd, wallet_location=wd, wallet_password=os.getenv('ORACLE_WALLET_PASSWORD'))
        _pool = oracledb.create_pool(**kw)
    return _pool

@contextmanager
def _conn():
    if KIND == 'oracle':
        with _get_pool().acquire() as c:
            yield c
    else:
        c = sqlite3.connect(SQLITE_PATH)
        try:
            yield c
        finally:
            c.close()

def _execute(cur, sql, p):
    if KIND == 'oracle' and 'payload' in p:
        cur.setinputsizes(payload=oracledb.DB_TYPE_CLOB)
    cur.execute(sql, p)

def query(sql, **p):
    with _conn() as c:
        cur = c.cursor()
        _execute(cur, sql, p)
        cols = [d[0].lower() for d in cur.description]
        return [dict(zip(cols, r)) for r in cur.fetchall()]

def one(sql, **p):
    rows = query(sql, **p)
    return rows[0] if rows else None

def run(sql, **p):
    with _conn() as c:
        cur = c.cursor()
        _execute(cur, sql, p)
        c.commit()
        return cur.rowcount

def insert(sql, **p):
    """INSERT that returns the new row id (table must have an id column)."""
    with _conn() as c:
        cur = c.cursor()
        if KIND == 'oracle':
            out = cur.var(oracledb.NUMBER)
            _execute(cur, sql + ' RETURNING id INTO :new_id', {**p, 'new_id': out})
            new_id = int(out.getvalue()[0])
        else:
            _execute(cur, sql, p)
            new_id = cur.lastrowid
        c.commit()
        return new_id

DDL_ORACLE = ["""CREATE TABLE app_users (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(100) NOT NULL,
  email VARCHAR2(254) NOT NULL UNIQUE,
  password_hash VARCHAR2(300) NOT NULL,
  user_role VARCHAR2(10) DEFAULT 'client' NOT NULL CHECK (user_role IN ('client','owner')),
  is_active NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  last_login TIMESTAMP)""",
"""CREATE TABLE content_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind VARCHAR2(10) NOT NULL CHECK (kind IN ('tech','project','post')),
  payload CLOB NOT NULL CONSTRAINT content_payload_json CHECK (payload IS JSON),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL)""",
"CREATE INDEX content_kind_idx ON content_items (kind)"]

DDL_SQLITE = ["""CREATE TABLE IF NOT EXISTS app_users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, full_name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL, user_role TEXT NOT NULL DEFAULT 'client', is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP, last_login TEXT)""",
"""CREATE TABLE IF NOT EXISTS content_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT, kind TEXT NOT NULL, payload TEXT NOT NULL,
  created_at TEXT DEFAULT CURRENT_TIMESTAMP)"""]

def init():
    """Create tables, load starter content once, and create the owner account."""
    with _conn() as c:
        cur = c.cursor()
        for ddl in (DDL_ORACLE if KIND == 'oracle' else DDL_SQLITE):
            try:
                cur.execute(ddl)
            except Exception as e:
                if 'ORA-00955' in str(e) or 'already exists' in str(e):
                    continue
                raise
        c.commit()
    seed = json.loads((BASE / 'seed_content.json').read_text(encoding='utf-8'))
    for kind in ('tech', 'project', 'post'):
        if one("SELECT COUNT(*) AS n FROM content_items WHERE kind = :k", k=kind)['n'] == 0:
            for item in seed.get(kind, []):
                insert("INSERT INTO content_items (kind, payload) VALUES (:k, :payload)",
                       k=kind, payload=json.dumps(item, ensure_ascii=False))
    em, pw = os.getenv('OWNER_EMAIL', '').strip().lower(), os.getenv('OWNER_PASSWORD', '')
    if em and pw:
        if not one("SELECT id FROM app_users WHERE email = :e", e=em):
            insert("INSERT INTO app_users (full_name, email, password_hash, user_role, is_active) VALUES (:n, :e, :h, 'owner', 1)",
                   n=os.getenv('OWNER_NAME', 'Owner'), e=em, h=generate_password_hash(pw))
            print('Owner account created:', em)
    elif not one("SELECT id FROM app_users WHERE user_role = 'owner'"):
        print('WARNING: no owner exists. Set OWNER_EMAIL and OWNER_PASSWORD and run init again.')
